function iconFor(node) {
  const raw = String((node && node.name) || "").toLowerCase();
  if (EXACT[raw]) return EXACT[raw];
  const bare = raw.replace(/^elite /, "");
  if (EXACT[bare]) return EXACT[bare];
  for (const [word, icon] of KEYWORDS) {
    if (raw.includes(word)) return icon;
  }
  if (node && node.useType === "Building") return "castle";
  if (node && node.useType === "Tech") return "scroll";
  return "sword";
}

